public class SessionManagement5ChangePassword extends HttpServlet {

  private static final long serialVersionUID = 1L;
  private static final Logger log = LogManager.getLogger(SessionManagement5ChangePassword.class);
  private static String levelName = "Session Management Challenge Five (Change Password)";

  // private static String levelResult = ""; //This Servlet does not return a result

  /**
   * Function used by Session Management Challenge Five to change the password of the account a
   * reset token was issued for. The token is the random secret generated by the set token servlet.
   *
   * @param newPassword the password which to use to update the accounts password
   * @param resetPasswordToken Single use reset token issued for the account
   */
  public void doPost(HttpServletRequest request, HttpServletResponse response)
      throws ServletException, IOException {
    // Setting IpAddress To Log and taking header for original IP if forwarded from proxy
    ShepherdLogManager.setRequestIp(request.getRemoteAddr(), request.getHeader("X-Forwarded-For"));
    HttpSession ses = request.getSession(true);

    // Translation Stuff
    Locale locale = new Locale(Validate.validateLanguage(request.getSession()));
    ResourceBundle errors = ResourceBundle.getBundle("i18n.servlets.errors", locale);
    ResourceBundle bundle =
        ResourceBundle.getBundle(
            "i18n.servlets.challenges.sessionManagement.sessionManagement5", locale);

    if (Validate.validateSession(ses)) {
      ShepherdLogManager.setRequestIp(
          request.getRemoteAddr(),
          request.getHeader("X-Forwarded-For"),
          ses.getAttribute("userName").toString());
      log.debug(levelName + " servlet accessed by: " + ses.getAttribute("userName").toString());
      PrintWriter out = response.getWriter();
      out.print(getServletInfo());
      String htmlOutput = new String();
      Connection conn = null;
      try {
        log.debug("Getting Challenge Parameters");
        Object passNewObj = request.getParameter("newPassword");
        Object tokenObj = request.getParameter("resetPasswordToken");
        Object userObj = request.getParameter("userName");
        String newPass = new String();
        String token = new String();
        String subName = new String();
        if (passNewObj != null) {
          newPass = (String) passNewObj;
        }
        if (tokenObj != null) {
          token = (String) tokenObj;
        }
        if (userObj != null) {
          subName = (String) userObj;
        }
        // The account to reset is the one the token was issued for. The name in the request is
        // answered rather than acted on: if it is a different account the reset is refused, so no
        // caller is told a reset succeeded for an account this never touched.
        String issuedToken = (String) ses.getAttribute(SessionManagement5SetToken.RESET_TOKEN);
        String userName = (String) ses.getAttribute(SessionManagement5SetToken.RESET_USER);
        Long issuedAt = (Long) ses.getAttribute(SessionManagement5SetToken.RESET_ISSUED);
        log.debug("userName = " + userName);

        boolean expired =
            issuedAt == null
                || System.currentTimeMillis() - issuedAt
                    > SessionManagement5SetToken.TOKEN_LIFE_MILLIS;

        if (issuedToken == null
            || userName == null
            || expired
            || !userName.equals(subName)
            || !MessageDigest.isEqual(
                issuedToken.getBytes(StandardCharsets.UTF_8),
                token.getBytes(StandardCharsets.UTF_8))) {
          log.debug("No matching reset token was issued for the submitted account, or it expired");
          htmlOutput = "<p>" + bundle.getString("changePass.oldToken") + "</p>";
        } else if (newPass.length() < 12) {
          log.debug("Invalid password submitted");
          htmlOutput = "<p>" + bundle.getString("changePass.failure") + "</p>";
        } else {
          log.debug("Getting ApplicationRoot");
          String ApplicationRoot = getServletContext().getRealPath("");
          log.debug("Servlet root = " + ApplicationRoot);

          conn = Database.getChallengeConnection(ApplicationRoot, "BrokenAuthAndSessMangChalFive");
          log.debug("Changing password for user: " + userName);
          PreparedStatement callstmt;

          callstmt =
              conn.prepareStatement("UPDATE users SET userPassword = SHA(?) WHERE userName = ?");

          callstmt.setString(1, newPass);
          callstmt.setString(2, userName);

          log.debug("Executing changePassword");
          callstmt.execute();

          log.debug("Committing changes made to database");
          callstmt = conn.prepareStatement("COMMIT");
          callstmt.execute();
          log.debug("Changes committed.");

          // A reset token is good for one password change only
          ses.removeAttribute(SessionManagement5SetToken.RESET_TOKEN);
          ses.removeAttribute(SessionManagement5SetToken.RESET_USER);
          ses.removeAttribute(SessionManagement5SetToken.RESET_ISSUED);

          htmlOutput = "<p>" + bundle.getString("changePass.success") + "</p>";
        }
        log.debug("Outputting HTML");
        out.write(htmlOutput);
      } catch (Exception e) {
        out.write(errors.getString("error.funky"));
        log.fatal(levelName + " - Change Password - " + e.toString());
      } finally {
        Database.closeConnection(conn);
      }
    } else {
      log.error(levelName + " servlet accessed with no session");
    }
  }
}
